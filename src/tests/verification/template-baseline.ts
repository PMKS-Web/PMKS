// PMKS's own decoded topology and solved joint positions for the five built-in
// templates, captured on staging before the Phase 0 solver refactor.
//
// This is NOT verification data: nothing here is checked against MATLAB or the
// PMKS fork (that lives in src/test-data/verification/). It is a self-snapshot
// whose only job is to fail loudly if a refactor changes what an existing
// shared URL decodes or solves to. The URL codec is a compatibility surface —
// every link anyone has ever shared depends on these numbers.
//
// Regenerate ONLY when a change to the numbers is intended and reviewed.
//
// Changed once, in Stage 1 of `docs/joint-type-and-cylinder-plan.md`, when a
// slider stopped being a prismatic joint, a coincident pin and a zero-length
// block joining them and became the one joint the canvas always drew. Three
// things moved, and this is the file where saying exactly which matters most.
//
// 1. **Sample rows for the joints that fold away are gone.** Every one of them
//    stood at exactly the coordinates of the joint it was coincident with, at
//    every sampled timestep, which is both what made them safe to drop and what
//    `template-url.spec.ts` goes on checking for every joint that is left.
//
// 2. **Seventeen payloads were regenerated, so the `joints` and `links`
//    snapshots of those moved with them.** They pin what the *stored* URL says,
//    and the stored URL is the short spelling now. `Slider_Crank` is the one to
//    look at: its `D` and its `CD` piston entry are gone, and `C` reads
//    `type: 0, isGrounded: true` where it read `type: 1, isGrounded: false`.
//    The payloads a release before Stage 1 actually shipped are frozen in
//    `src/test-data/legacy-payloads.ts`, with a spec decoding each against its
//    regenerated twin -- that, rather than this file, is what says the old
//    strings still open as the mechanism they were.
//
// 3. **Two solved numbers were re-pinned**, both on Cylinder_Gripper and both
//    toward the symmetry that drawing has. See the comment on `D` below.
//
// Changed a second time, in Stage 2c of the same plan, when a cylinder's seal
// became the square a reader selects and so earned a letter (decision S9).
// **Three sample ids moved and no number did**: `Excavator_Bucket`'s `A2` reads
// `M`, `Hood_Hinge`'s `A2` reads `P`, `Aircraft_Landing_Gear`'s `I2` reads `R`.
// Each of those three was drawn in the app and pasted in as the URL it wrote,
// back when a seal was hidden and took an interior name; the reader gives such
// a seal the next free letter as the last step of the build. The `joints` and
// `links` snapshots above each one are untouched, because they pin what the
// *stored* URL says and the codec did not change -- which is the clearest
// evidence there is that this was a rename and nothing else.
//
// Changed a third time for #308, when two of those three were redrawn at the size
// of the machines they were traced from: the landing gear in meters at 0.4
// times its centimeter numbers (forty times the size), and the hood hinge in
// centimeters four times larger. **Every number was multiplied by its factor
// and nothing else moved**: the step counts and the
// picks are the ones they were, and each solved position is the old one times
// the factor to within the 2e-4 the solver's rounding allows. The payloads were
// re-encoded by the current writer rather than edited, so the `joints` and
// `links` snapshots also lose the seal's coincident interior record (`A3`,
// `I3`) and carry the seal under the letter the reader had already been giving
// it (`P`, `R`), which is the rename described just above. The excavator was
// left at its traced size: drawn more than a few times larger, two of its
// rates near a toggle come out 1.5 times outside the numerical oracle's
// budget, the same amount at every size from twenty times to a hundred.

export interface TemplateJointSnapshot {
  id: string;
  type: number;
  x: number;
  y: number;
  isGrounded: boolean;
  isInput: boolean;
  isWelded: boolean;
  angleRadians: number;
}

export interface TemplateLinkSnapshot {
  id: string;
  type: number;
  jointIDs: string[];
  subsetLinkIDs: string[];
}

export interface TemplateBaseline {
  joints: TemplateJointSnapshot[];
  links: TemplateLinkSnapshot[];
  /** Solved timestep count. */
  steps: number;
  /** Timestep indices the samples were taken at. */
  picks: number[];
  /** Per pick: [jointId, x, y] for every joint, in mechanism order. */
  samples: [string, number, number][][];
}

